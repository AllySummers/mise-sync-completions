const hasZsh = await new Deno.Command('zsh', {
  args: ['-fc', 'true'],
  stdout: 'null',
  stderr: 'null',
})
  .output()
  .then((r) => r.success, () => false);

Deno.test({
  name: 'smoke: a fallback file loads in an isolated zsh through fpath and compinit',
  ignore: !hasZsh,
  fn: async () => {
    const h = await harness();
    try {
      await h.tools({ deno: { version: '2.1.0' } });
      await h.run();
      const script = `fpath=(${h.out('zsh')} $fpath); autoload -Uz compinit; compinit -u -D; ` +
        'print -r -- ${_comps[deno]}';
      const result = await new Deno.Command('zsh', {
        args: ['-fc', script],
        env: { HOME: h.root, ZDOTDIR: h.root },
        stdout: 'piped',
        stderr: 'piped',
      }).output();
      assert.equal(new TextDecoder().decode(result.stdout).trim(), '_deno');
    } finally {
      await h.cleanup();
    }
  },
});
