test('concurrent runs keep every record', async (h) => {
  await h.tools({ deno: { version: '2.1.0' } });
  await Promise.all((['zsh', 'bash', 'fish'] as const).map((shell) => h.run({ shell })));
  const records = Object.values((await h.state()).outputs) as {
    sync_name: string;
    shell: string;
  }[];
  assert.deepEqual(
    records.filter((r) => r.sync_name === 'deno').map((r) => r.shell).sort(),
    ['bash', 'fish', 'zsh'],
  );
});

