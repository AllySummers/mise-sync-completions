test('files this task never wrote are left alone at handoff', async (h) => {
  await h.tools({ hk: { version: '2.4.0' }, usage: { version: '6.12.0' } });
  await nativeHk(h);
  await writeInstall(join(h.install('usage'), '6.12.0'), {
    bins: ['usage'],
    ...assetCompletions('usage'),
  });
  await Deno.mkdir(h.out('zsh'), { recursive: true });
  await Deno.writeTextFile(h.file('zsh', '_hk'), '# from elsewhere\n');
  await Deno.writeTextFile(join(h.root, 'usage-target'), '# linked\n');
  await Deno.symlink(join(h.root, 'usage-target'), h.file('zsh', '_usage'));

  assert.match(await h.run(), /native: 2/);
  assert.equal(await Deno.readTextFile(h.file('zsh', '_hk')), '# from elsewhere\n');
  assert.ok(await exists(h.file('zsh', '_usage')));
});

test('aliases sharing an output file get one deterministic owner', async (h) => {
  await h.tools({ rg: { version: '15.0.0' }, ripgrep: { version: '15.0.0' } });
  const out = await h.run();
  assert.match(out, /shadow ripgrep: rg owns zsh\/_rg/);
  const calls = (await h.calls()).map((c) => c.args);
  assert.ok(calls.includes('x rg@15.0.0 -- rg --generate complete-zsh'));
  assert.ok(!calls.some((c) => c.includes('ripgrep@')));
  assert.equal((await h.state()).outputs[h.file('zsh', '_rg')].sync_name, 'rg');
});

test('a backend alias writes under the command name in every shell', async (h) => {
  await h.tools({ 'github:railwayapp/cli': { version: '4.10.0' } });
  for (const shell of ['zsh', 'bash', 'fish'] as const) {
    await h.run({ shell });
  }
  const calls = (await h.calls()).map((c) => c.args);
  assert.ok(calls.includes('x github:railwayapp/cli@4.10.0 -- railway completion zsh'));
  assert.ok(await exists(h.file('zsh', '_railway')));
  assert.ok(await exists(h.file('bash', 'railway')));
  assert.ok(await exists(h.file('fish', 'railway.fish')));
  assert.equal(await exists(h.file('zsh', '_cli')), false);
  assert.equal((await h.state()).outputs[h.file('zsh', '_railway')].command, 'railway');

  await h.tools({
    'github:railwayapp/cli': { version: '4.10.0' },
    railway: { version: '4.10.0' },
  });
  assert.match(await h.run(), /shadow github:railwayapp\/cli: railway owns zsh\/_railway/);
  assert.equal((await h.state()).outputs[h.file('zsh', '_railway')].sync_name, 'railway');
});

test('generation uses the installed global selection outside the caller project', async (h) => {
  await h.tools({
    deno: [{ version: '2.0.0', active: false }, { version: '2.1.0' }],
    jj: { version: '0.30.0', installed: false },
  });
  await h.run();
  const calls = await h.calls();
  assert.ok(calls.some((c) => c.args === 'x deno@2.1.0 -- deno completions zsh'));
  assert.ok(!calls.some((c) => c.args.includes('jj')));
  assert.ok(calls.every((c) => c.cwd === '/'));
});

test('reconciliation removes only proven files, never on a failed or empty inventory', async (h) => {
  await h.tools({ deno: { version: '2.1.0' }, jj: { version: '0.30.0' } });
  await h.run();

  await Deno.remove(Deno.env.get('FAKE_MISE_LS')!);
  await h.run();
  await Deno.writeTextFile(Deno.env.get('FAKE_MISE_LS')!, '{}');
  await h.run();
  assert.ok(await exists(h.file('zsh', '_deno')));
  assert.ok(await exists(h.file('zsh', '_jj')));

  await h.tools({ deno: { version: '2.1.0' } });
  assert.match(await h.run(), /remove jj/);
  assert.equal(await exists(h.file('zsh', '_jj')), false);

  await Deno.writeTextFile(h.file('zsh', '_deno'), '# edited\n');
  await h.tools({ jj: { version: '0.30.0' } });
  assert.match(await h.run(), /_deno changed since it was written; preserved/);
  assert.equal(await Deno.readTextFile(h.file('zsh', '_deno')), '# edited\n');
});

